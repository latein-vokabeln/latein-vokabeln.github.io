// { 1: { label: 'Lektion 1', short: 'L1', color, topics: [{ name, words: [{ la, de }] }] }, … }
export const vocabByGrade = Object.fromEntries(LESSONS.map((lesson, i) => [i + 1, {
  label: `Lektion ${i + 1}`,
  short: `L${i + 1}`,
  color: COLORS[i % COLORS.length],
  topics: [{ name: lesson.title, words: lesson.words.map(([la, de]) => ({ la, de })) }],
}]));

// Display order of the lessons (same as on the home page)
export const GRADE_ORDER = LESSONS.map((_, i) => i + 1);

export const sortGrades = (grades) =>
  [...grades].sort((a, b) => GRADE_ORDER.indexOf(a) - GRADE_ORDER.indexOf(b));

// „Lektion 3“, „Lektion 1 + 2“, „Lektion 1–4“, „Lektion 1–3 + 7“ …
export function formatGradeLabel(grades) {
  const sorted = sortGrades(grades);
  const parts = [];
  for (let i = 0; i < sorted.length; i++) {
    let j = i;
    while (j + 1 < sorted.length && sorted[j + 1] === sorted[j] + 1) j++;
    parts.push(j - i >= 2 ? `${sorted[i]}–${sorted[j]}` : sorted.slice(i, j + 1).join(' + '));
    i = j;
  }
  return `Lektion ${parts.join(' + ')}`;
}

// Some words appear in several lessons (e.g. again with their perfect form).
// Word lists for practice, tests and games contain each pair once.
export function uniqueWords(words) {
  const seen = new Set();
  return words.filter(w => {
    const k = `${w.la}|${w.de}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

export function buildWordPool(grades) {
  return uniqueWords(grades.flatMap(g => {
    const grade = vocabByGrade[g];
    if (!grade) return [];
    return grade.topics.flatMap(t =>
      t.words.map(w => ({ ...w, grade: g, topic: t.name }))
    );
  }));
}
